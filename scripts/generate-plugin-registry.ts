import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const PLUGINS_DIR = join(ROOT, "src", "plugins", "reports");
const OUT_FILE = join(ROOT, "src", "services", "reports", "registry.generated.ts");

// Keep canonical ordering of existing built-in reports, then sort new plugins alphabetically.
const PREFERRED_ORDER = [
  "sign-in-anomalies",
  "risky-users",
  "mfa-registration",
  "inactive-guest-users",
  "dormant-licensed-users",
  "security-alerts-digest",
  "dlp-alerts",
  "conditional-access-failures",
  "license-utilization",
  "app-secrets-expiry",
  "device-compliance",
  "audit-log-summary",
  "secure-score",
  "provisioning-summary",
  "risky-service-principals",
  "teams-user-activity",
  "mailbox-quota",
  "m365-groups-activity",
  "onedrive-usage",
  "sharepoint-site-usage",
  "active-users-counts",
  "risk-detections",
  "sp-risk-detections",
  "custom-attr-audits",
  "sp-sign-ins",
  "manual-graph-query",
];

function discoverPluginFolders(): string[] {
  if (!existsSync(PLUGINS_DIR)) return [];
  const rank = new Map(PREFERRED_ORDER.map((id, idx) => [id, idx]));
  return readdirSync(PLUGINS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(PLUGINS_DIR, d.name, "plugin.ts")))
    .map((d) => d.name)
    .sort((a, b) => {
      const ra = rank.get(a);
      const rb = rank.get(b);
      if (ra !== undefined && rb !== undefined) return ra - rb;
      if (ra !== undefined) return -1;
      if (rb !== undefined) return 1;
      return a.localeCompare(b);
    });
}

function toVarName(id: string, index: number): string {
  const safe = id.replace(/[^a-zA-Z0-9]/g, "_");
  return `plugin_${index}_${safe}`;
}

export function generateRegistrySource(): { folders: string[]; source: string } {
  const folders = discoverPluginFolders();
  const imports = folders.map(
    (id, i) => `import { plugin as ${toVarName(id, i)} } from "@/plugins/reports/${id}/plugin";`,
  );
  const items = folders.map((id, i) => `  ${toVarName(id, i)},`);

  const source = [
    "// AUTO-GENERATED by scripts/generate-plugin-registry.ts — DO NOT EDIT MANUALLY.",
    "// Run `bun run plugin:sync` after adding or removing a folder in src/plugins/reports/.",
    'import type { ReportPlugin } from "./types";',
    ...imports,
    "",
    "export const BUILTIN_REPORT_PLUGINS: ReportPlugin<object>[] = [",
    ...items,
    "] as ReportPlugin<object>[];",
    "",
  ].join("\n");

  return { folders, source };
}

if (import.meta.main) {
  const checkOnly = process.argv.includes("--check");
  const { folders, source } = generateRegistrySource();
  const existing = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : "";

  if (checkOnly) {
    if (existing !== source) {
      console.error(
        `[plugins] Registry is out of date (${folders.length} plugin(s)). Run: bun run plugin:sync`,
      );
      process.exit(1);
    }
    console.log(`[plugins] Registry up to date (${folders.length} built-in plugin(s)).`);
  } else {
    writeFileSync(OUT_FILE, source, "utf8");
    console.log(`[plugins] Generated ${OUT_FILE} with ${folders.length} built-in plugin(s).`);
  }
}
